"""Generate the Unreal port's FSM state list and legality table from Godot's.

Run from a shell (plain Python 3):
    python3 tools/unreal/export_fsm.py "<UE project>/Source/MyProject2/AegisFSMStates.h"
With no argument the header is written to stdout.

game/core/fsm/wrestler_fsm.gd is the contract (gauntlet/anchor/ARCHITECTURE.md,
"The FSM is authoritative"): its `enum State` and `LEGAL_TRANSITIONS`. This
script copies both verbatim -- same names, same order, same numbers -- into
EAegisFSMState and one bitmask per state, so a transition legal in one engine
is legal in the other. Re-run it whenever wrestler_fsm.gd changes; never edit
the header by hand. Output is deterministic.
"""
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FSM = os.path.join(REPO, "game", "core", "fsm", "wrestler_fsm.gd")


def parse(src: str):
    enum_body = re.search(r"enum State \{(.*?)\n\}", src, re.S).group(1)
    # strip ## doc comments, keep identifiers in order
    states = re.findall(r"^\s*([A-Z_]+),", re.sub(r"#.*", "", enum_body), re.M)
    table_body = re.search(r"const LEGAL_TRANSITIONS := \{(.*?)\n\}", src, re.S).group(1)
    legal = {}
    for m in re.finditer(r"^\s*State\.([A-Z_]+):\s*\[(.*?)\],?\s*$", table_body, re.M):
        legal[m.group(1)] = re.findall(r"State\.([A-Z_]+)", m.group(2))
    missing = [s for s in states if s not in legal]
    if missing:
        raise SystemExit("states with no LEGAL_TRANSITIONS entry: %s" % missing)
    for frm, tos in legal.items():
        for t in tos:
            if t not in states:
                raise SystemExit("%s -> unknown state %s" % (frm, t))
    if len(states) > 32:
        raise SystemExit("%d states no longer fit a uint32 mask" % len(states))
    return states, legal


def render(states, legal) -> str:
    idx = {s: i for i, s in enumerate(states)}
    lines = [
        "// GENERATED by aegis/tools/unreal/export_fsm.py from game/core/fsm/wrestler_fsm.gd.",
        "// Do not edit by hand: change wrestler_fsm.gd and re-run the script.",
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        '#include "AegisFSMStates.generated.h"',
        "",
        "/** WrestlerFSM.State, in Godot's order (the numbers match). */",
        "UENUM(BlueprintType)",
        "enum class EAegisFSMState : uint8",
        "{",
    ]
    for s in states:
        lines.append("    %s," % s)
    lines += [
        "    Count UMETA(Hidden)",
        "};",
        "",
        "namespace AegisFSM",
        "{",
        "/** WrestlerFSM.LEGAL_TRANSITIONS: bit N of LegalMask(From) set means From -> state N is legal. */",
        "inline uint32 LegalMask(EAegisFSMState From)",
        "{",
        "    static constexpr uint32 Masks[] = {",
    ]
    for s in states:
        mask = 0
        for t in legal[s]:
            mask |= 1 << idx[t]
        targets = ", ".join(legal[s]) or "nothing (terminal)"
        lines.append("        0x%08Xu, // %s -> %s" % (mask, s, targets))
    lines += [
        "    };",
        "    static_assert(UE_ARRAY_COUNT(Masks) == (int32)EAegisFSMState::Count, \"one mask per state\");",
        "    const int32 I = (int32)From;",
        "    return I >= 0 && I < (int32)EAegisFSMState::Count ? Masks[I] : 0u;",
        "}",
        "",
        "inline bool IsLegal(EAegisFSMState From, EAegisFSMState To)",
        "{",
        "    return (LegalMask(From) >> (uint32)To) & 1u;",
        "}",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    states, legal = parse(open(FSM).read())
    text = render(states, legal)
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", newline="\n") as f:
            f.write(text)
        print("wrote %s: %d states" % (sys.argv[1], len(states)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
